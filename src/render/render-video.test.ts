/** ffprobe's JSON, narrowed once at the process boundary so no `any` reaches an assertion. */
const ProbeOutputSchema = z.object({
  streams: z.array(z.record(z.string(), z.unknown())).min(1),
});

/** ffprobe as values: the integration test asserts the file, not the encoder's own receipt. */
const probe = (path: string): Record<string, unknown> => {
  const stdout = execFileSync('ffprobe', [
    '-v',
    'error',
    '-select_streams',
    'v:0',
    '-show_entries',
    'stream=codec_name,width,height,r_frame_rate,avg_frame_rate,nb_frames,duration,format_name,pix_fmt,color_range',
    '-of',
    'json',
    path,
  ]).toString();
  const parsed = ProbeOutputSchema.parse(JSON.parse(stdout));
  const stream = parsed.streams[0];
  if (stream === undefined) throw new Error('ffprobe reported no video stream');
  return stream;
};

const decodeToRgb = (path: string): Buffer =>
  execFileSync(
    'ffmpeg',
    [
      '-y',
      '-hide_banner',
      '-loglevel',
      'error',
      '-i',
      path,
      '-f',
      'rawvideo',
      '-pix_fmt',
      'rgb24',
      '-',
    ],
    { maxBuffer: 64 * 1024 * 1024 },
  );

const extractFrame = (video: string, frame: number, target: string): void => {
  execFileSync('ffmpeg', [
    '-y',
    '-hide_banner',
    '-loglevel',
    'error',
    '-i',
    video,
    '-vf',
    `select=eq(n\\,${String(frame)})`,
    '-fps_mode',
    'passthrough',
    '-frames:v',
    '1',
    target,
  ]);
};

/** Mean and worst channel difference between two equal-sized RGB buffers. */
const compare = (a: Buffer, b: Buffer): { mean: number; max: number } => {
  expect(a.length).toBe(b.length);
  let total = 0;
  let max = 0;
  for (let index = 0; index < a.length; index++) {
    const difference = Math.abs((a[index] ?? 0) - (b[index] ?? 0));
    total += difference;
    if (difference > max) max = difference;
  }
  return { mean: total / a.length, max };
};

const asyncIterableOf = <T>(items: readonly T[]): AsyncIterable<T> => ({
  [Symbol.asyncIterator]: () => {
    const iterator = items[Symbol.iterator]();
    return { next: () => Promise.resolve(iterator.next()) };
  },
});

const SAMPLE_RATE = 48_000;

/** A local test clip: generated by FFmpeg, never committed (example asset licensing ADR). */
const generateSine = (path: string, seconds: number, frequency: number, channels = 1): void => {
  const tone = `0.6*sin(2*PI*${String(frequency)}*t)`;
  // Two expressions is a stereo source with the same level in each channel; one is mono.
  const expression = channels === 2 ? `${tone}|${tone}` : tone;
  execFileSync('ffmpeg', [
    '-y',
    '-hide_banner',
    '-loglevel',
    'error',
    '-f',
    'lavfi',
    // `aevalsrc` rather than `sine`, whose amplitude is not settable in FFmpeg 9.
    '-i',
    `aevalsrc=${expression}:d=${String(seconds)}:s=${String(SAMPLE_RATE)}`,
    '-c:a',
    'pcm_s16le',
    path,
  ]);
};

/** The MP4's audio stream, probed as data: codec, rate, channels and its own duration. */
const probeAudio = (path: string): Record<string, unknown> => {
  const stdout = execFileSync('ffprobe', [
    '-v',
    'error',
    '-select_streams',
    'a:0',
    '-show_entries',
    'stream=codec_name,sample_rate,channels,duration',
    '-of',
    'json',
    path,
  ]).toString();
  const parsed = ProbeOutputSchema.parse(JSON.parse(stdout));
  const stream = parsed.streams[0];
  if (stream === undefined) throw new Error('ffprobe reported no audio stream');
  return stream;
};

/** Decoded mono PCM of the file's audio stream, so the assertions see energy, not metadata. */
const pcmOf = (path: string): Int16Array => {
  const bytes = execFileSync(
    'ffmpeg',
    [
      '-y',
      '-hide_banner',
      '-loglevel',
      'error',
      '-i',
      path,
      '-vn',
      '-ac',
      '1',
      '-ar',
      String(SAMPLE_RATE),
      '-f',
      's16le',
      '-',
    ],
    { maxBuffer: 64 * 1024 * 1024 },
  );
  return new Int16Array(bytes.buffer, bytes.byteOffset, Math.floor(bytes.byteLength / 2));
};

/** RMS over `[from, to)` seconds of decoded PCM; -1 dBFS-weighted silence is near zero. */
const rmsIn = (samples: Int16Array, from: number, to: number): number => {
  const start = Math.max(0, Math.round(from * SAMPLE_RATE));
  const end = Math.min(samples.length, Math.round(to * SAMPLE_RATE));
  let square = 0;
  for (let index = start; index < end; index++) {
    const value = (samples[index] ?? 0) / 32768;
    square += value * value;
  }
  return end > start ? Math.sqrt(square / (end - start)) : 0;
};

/** Energy onsets: the first 5 ms window above the threshold after a quiet one. */
const onsetsOf = (samples: Int16Array, threshold = 0.02): number[] => {
  const window = Math.round(SAMPLE_RATE * 0.005);
  const onsets: number[] = [];
  let loud = false;
  for (let start = 0; start + window <= samples.length; start += window) {
    const windowLoud =
      rmsIn(samples, start / SAMPLE_RATE, (start + window) / SAMPLE_RATE) > threshold;
    if (windowLoud && !loud) onsets.push(start / SAMPLE_RATE);
    loud = windowLoud;
  }
  return onsets;
};

