    expect(onsets).toHaveLength(2);
    expect(Math.abs((onsets[0] ?? Number.NaN) - 0)).toBeLessThanOrEqual(1 / 20);
    expect(Math.abs((onsets[1] ?? Number.NaN) - 1)).toBeLessThanOrEqual(1 / 20);
