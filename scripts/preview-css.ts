// Compiles the preview host page's Tailwind stylesheet (src/preview/styles.css) into a TypeScript
// module exporting it as a string, src/preview/styles.generated.ts. The host bundle is served by
// the user's Vite, which has no Tailwind plugin, so the page injects the compiled CSS itself. Run
// with Node.js 24.2+ from the repository root; `pnpm build` runs it before tsdown:
//
//   node scripts/preview-css.ts
//
// Only the class names in src/preview/**/*.tsx are scanned (`source(none)` in the stylesheet turns
// off automatic detection). The output is gitignored and regenerated on every build.
//
// It calls `tailwindcss` directly rather than `@tailwindcss/node`: the latter depends on
// lightningcss, which is MPL-2.0 and, once installed, also resolves as Vite's optional peer in the
// production closure (docs/contexts/render/adr/20261024-bundled-vite.accepted.md). Without it the
// output is left unminified.
import { Scanner } from '@tailwindcss/oxide';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'tailwindcss';
import { z } from 'zod';

const repositoryRoot = fileURLToPath(new URL('..', import.meta.url));
const input = join(repositoryRoot, 'src/preview/styles.css');
const output = join(repositoryRoot, 'src/preview/styles.generated.ts');

const Manifest = z.object({
  exports: z
    .record(z.string(), z.union([z.string(), z.object({ style: z.string().optional() })]))
    .optional(),
});

// A bare `@import` names a package (`tailwindcss`, `tw-animate-css`) whose `exports` maps the
// subpath to a .css file, directly or under the `style` condition.
const packageStylesheet = (id: string): string => {
  const parts = id.split('/');
  const nameLength = id.startsWith('@') ? 2 : 1;
  const directory = join(repositoryRoot, 'node_modules', ...parts.slice(0, nameLength));
  const manifest = Manifest.parse(
    JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8')),
  );
  const target = manifest.exports?.[['.', ...parts.slice(nameLength)].join('/')];
  const file = typeof target === 'string' ? target : target?.style;
  if (file === undefined) throw new Error(`No stylesheet export for ${id}`);
  return join(directory, file);
};

const compiler = await compile(readFileSync(input, 'utf8'), {
  base: dirname(input),
  loadStylesheet: (id, base) => {
    const path = id.startsWith('.') ? resolve(base, id) : packageStylesheet(id);
    return Promise.resolve({ path, base: dirname(path), content: readFileSync(path, 'utf8') });
  },
});
const scanner = new Scanner({
  sources: [{ base: repositoryRoot, pattern: 'src/preview/**/*.tsx', negated: false }],
});
const css = compiler.build(scanner.scan());
writeFileSync(
  output,
  `// Generated by scripts/preview-css.ts from src/preview/styles.css. Do not edit.\nexport const previewCss: string = ${JSON.stringify(css)};\n`,
);
